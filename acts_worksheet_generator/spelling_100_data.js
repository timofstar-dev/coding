// 랜덤 7문항 생성 함수 (선택형 6문제 + 띄어쓰기 1문제, 꿀팁 3개 추출)
function getRandomBareunSpellingSet(setType = 'random100') {
    let selectedItems = [];
    
    if (bareunCuratedSets[setType]) {
        const targetIds = bareunCuratedSets[setType].ids;
        selectedItems = targetIds.map(id => bareunSpelling100.find(item => item.id === id));
    } else {
        // 완전 무작위 7문항: 띄어쓰기 1문항 + 선택형 6문항
        const spacingPool = bareunSpelling100.filter(item => item.category === 'spacing' || item.isSpacing);
        const choicePool = bareunSpelling100.filter(item => item.category !== 'spacing' && !item.isSpacing);
        
        // 셔플
        const shuffledSpacing = [...spacingPool].sort(() => Math.random() - 0.5);
        const shuffledChoice = [...choicePool].sort(() => Math.random() - 0.5);
        
        const pickedSpacing = shuffledSpacing[0];
        const pickedChoices = shuffledChoice.slice(0, 6);
        
        // 1~6번은 선택형, 7번은 띄어쓰기로 배치
        selectedItems = [...pickedChoices, pickedSpacing];
    }

    // 번호 부여 및 문제 구성
    const questions = selectedItems.map((item, idx) => {
        return {
            num: idx + 1,
            text: item.text,
            answer: item.answer,
            options: item.options || [],
            isSpacing: !!(item.isSpacing || item.category === 'spacing'),
            tip: item.tip,
            explanation: item.explanation
        };
    });

    // 꿀팁 3개 무작위 또는 대표 추출 (팁이 있는 문항 중)
    const tipsWithContent = questions.filter(q => q.tip).map(q => q.tip);
    const uniqueTips = Array.from(new Set(tipsWithContent));
    const finalTips = uniqueTips.slice(0, 3);

    // 교사용 정답 문자열 생성
    const answerGuide = questions.map(q => `${q.num}) ${q.answer}`).join(' ');

    return {
        questions: questions,
        tips: finalTips,
        answerGuide: answerGuide
    };
}
